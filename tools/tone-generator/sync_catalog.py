"""Writes docs/assets/generator/catalog.js from the app's own block definitions.

The tone generator runs in a browser, so it can't read Rust. This copies each
block's parameter ranges out of crates/amp-dsp/src/block.rs, and the factory tones
out of factory-tones.json. CI runs it with --check, so a changed parameter stops
the docs deploy until the generator is updated too.

To refresh factory-tones.json, serialize `amp_preset::factory_tones()` to JSON.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BLOCK_SOURCE = ROOT / "crates/amp-dsp/src/block.rs"
FACTORY_TONES = Path(__file__).with_name("factory-tones.json")
OUTPUT = ROOT / "docs/assets/generator/catalog.js"

SCHEMA_VERSION = re.compile(r"SCHEMA_VERSION: u32 = (\d+);")
CONSTANT = re.compile(r"const (\w+): &\[ParamSpec\] = &\[(.*?)\];", re.DOTALL)
PARAM = re.compile(
    r'param\("(\w+)", "([^"]*)", "([^"]*)", (-?[\d.]+), (-?[\d.]+), (-?[\d.]+)\)'
)
ARM = re.compile(r"Self::(\w+)(?: \| Self::(\w+))? => ([A-Z]+),")
TITLE = re.compile(r'Self::(\w+) => "([^"]+)",')


def snake(name):
    return re.sub(r"(?<!^)([A-Z])", r"_\1", name).lower()


def number(text):
    value = float(text)
    return int(value) if value.is_integer() else value


def blocks():
    source = BLOCK_SOURCE.read_text(encoding="utf-8")
    params = {
        name: [
            {
                "id": id,
                "name": label,
                "unit": unit,
                "min": number(low),
                "max": number(high),
                "default": number(default),
            }
            for id, label, unit, low, high, default in PARAM.findall(body)
        ]
        for name, body in CONSTANT.findall(source)
    }
    titles = {snake(kind): title for kind, title in TITLE.findall(source)}
    found = {}
    for first, second, constant in ARM.findall(source):
        for kind in filter(None, (first, second)):
            found[snake(kind)] = {
                "title": titles[snake(kind)],
                "params": params[constant],
            }
    return found


def schema():
    source = (ROOT / "crates/amp-preset/src/preset.rs").read_text(encoding="utf-8")
    return int(SCHEMA_VERSION.search(source).group(1))


def render():
    examples = json.loads(FACTORY_TONES.read_text(encoding="utf-8-sig"))
    catalog = {"schema": schema(), "blocks": blocks(), "examples": examples}
    body = json.dumps(catalog, indent=1, ensure_ascii=False)
    return (
        "// Generated by tools/tone-generator/sync_catalog.py. Don't edit by hand.\n"
        f"globalThis.AmpToneCatalog = {body};\n"
    )


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUTPUT} is out of date. Run tools/tone-generator/sync_catalog.py")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
